import {chromium} from 'playwright-core';
import assert from 'node:assert/strict';
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto('http://127.0.0.1:8000');
 await page.getByLabel('Choose a synthetic identity').selectOption('north-engineer');
 await page.getByRole('button',{name:'Enter workspace'}).click();
 await page.getByRole('button',{name:'Integration profiles',exact:true}).click();
 await page.getByRole('button',{name:'New profile',exact:true}).click();
 await page.getByLabel('Profile name',{exact:true}).fill('Browser handover '+Date.now());
 await page.getByRole('button',{name:'Add mapping',exact:true}).click();
 await page.getByLabel('Source field 4',{exact:true}).selectOption('status');
 await page.getByLabel('Destination field 4',{exact:true}).fill('handover.status');
 await page.getByLabel('Value conversion 4',{exact:true}).fill('{"approved":"Released"}');
 await page.getByLabel('Value conversion 4',{exact:true}).press('Tab');
 await page.getByRole('button',{name:'Save profile',exact:true}).click();
 await page.getByText('Saved immutable version 1. Separate review is required.').waitFor();
 await page.getByLabel('Test identity').selectOption('north-approver');
 await page.getByRole('button',{name:'Approve profile version',exact:true}).click();
 await page.getByText('Profile version approved. No integration was executed.').waitFor();
 await page.getByLabel('Test identity').selectOption('north-engineer');
 await page.getByRole('button',{name:'Handovers',exact:true}).click();
 await page.getByLabel('Select C-005',{exact:true}).check();
 await page.getByRole('button',{name:'Create handover preview (1)',exact:true}).click();
 await page.getByText('Fixed synthetic manifest created. No document was downloaded or transferred.').waitFor();
 await page.getByText('Released',{exact:false}).first().waitFor();
 await page.getByLabel('Test identity').selectOption('north-approver');
 await page.getByRole('button',{name:'Approve synthetic manifest',exact:true}).first().click();
 await page.getByText('Synthetic manifest approved. Zero files transferred; live execution is unavailable.').waitFor();
 await page.screenshot({path:'../.local/screenshots/handovers.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.getByLabel('Test identity').selectOption('south-viewer');
 await page.getByRole('heading',{name:'Select a profile first',exact:true}).waitFor();
 assert.equal(await page.getByText('Released',{exact:true}).count(),0);
 assert.deepEqual(errors,[]);
 console.log('Integration browser smoke passed: four-field mapping, value conversion, separate profile approval, selected-document manifest, separate manifest approval, mobile and tenant isolation; no JavaScript errors.');
}finally{await browser.close();}
