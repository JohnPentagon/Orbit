// Real local persistence and permissions; Meridian preview is an offline fixture.
import {chromium} from 'playwright-core';
import assert from 'node:assert/strict';
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1100},acceptDownloads:true});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto('http://127.0.0.1:8000');
 await page.getByLabel('Choose a synthetic identity').selectOption('north-owner');
 await page.getByRole('button',{name:'Enter workspace'}).click();
 await page.getByRole('button',{name:'Connection preparation',exact:true}).click();
 const name='Meridian smoke '+Date.now();
 await page.getByLabel('Plan name',{exact:true}).fill(name);
 await page.getByLabel('Deployment',{exact:true}).selectOption('on_premises');
 await page.getByLabel('Integration interface',{exact:true}).selectOption('Explorer Web API (read)');
 await page.getByLabel('Execution route',{exact:true}).selectOption('local_network');
 await page.getByLabel('Planned API URL',{exact:true}).fill('https://meridian.internal.example:8443/BCEnterprise');
 await page.getByLabel('Test status: edition',{exact:true}).selectOption('blocked');
 await page.getByLabel('Test evidence: edition',{exact:true}).fill('Synthetic UI check — awaiting administrator release information');
 await page.getByRole('button',{name:'Save connection plan',exact:true}).click();
 await page.getByText('Plan and manual test evidence saved. No vendor request was made.').waitFor();
 let card=page.locator('.read-connection').filter({has:page.getByRole('heading',{name,exact:true})});
 assert.match(await card.innerText(),/blocked/);
 await card.getByRole('button',{name:'Preview Explorer fixture',exact:true}).click();
 await page.getByRole('heading',{name:'Meridian Explorer · SYNTHETIC FIXTURE',exact:true}).waitFor();
 assert.match(await card.innerText(),/0\/15 checks passed/);
 await page.reload();
 await page.getByRole('button',{name:'Connection preparation',exact:true}).click();
 card=page.locator('.read-connection').filter({has:page.getByRole('heading',{name,exact:true})});
 await card.getByRole('button',{name:'Edit plan & checklist',exact:true}).click();
 assert.equal(await page.getByLabel('Test status: edition',{exact:true}).inputValue(),'blocked');
 await page.getByLabel('Test status: scope',{exact:true}).selectOption('passed');
 await page.getByLabel('Test evidence: scope',{exact:true}).fill('Synthetic UI regression evidence only');
 await page.getByRole('button',{name:'Save plan revision',exact:true}).click();
 await page.getByText('Plan and manual test evidence saved. No vendor request was made.').waitFor();
 await card.getByRole('button',{name:'Edit plan & checklist',exact:true}).click();
 await page.getByLabel('Planned API URL',{exact:true}).fill('https://other.internal.example/BCEnterprise');
 await page.getByRole('button',{name:'Save plan revision',exact:true}).click();
 await page.getByText(/previous checks were reset to untested/).waitFor();
 assert.match(await card.innerText(),/0\/15 checks passed/);
 const downloadPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:'Export checklist',exact:true}).click();
 const download=await downloadPromise;assert.equal(download.suggestedFilename(),'orbit-harbour-connection-checklist.json');
 const stream=await download.createReadStream();let raw='';for await(const chunk of stream)raw+=chunk.toString();
 const exported=JSON.parse(raw);assert.equal(exported.project,'harbour');assert.ok(exported.plans.some(p=>p.configuration.name===name));
 await page.getByLabel('Test identity').selectOption('north-viewer');
 await page.getByText('viewer · north-viewer',{exact:true}).waitFor();
 await page.getByRole('heading',{name:'Connection preparation & testing',exact:true}).waitFor();
 assert.equal(await page.getByLabel('Plan name',{exact:true}).count(),0);
 await page.screenshot({path:'../.local/screenshots/connection-preparation.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('Connection preparation smoke passed: save/reload, manual evidence, offline preview, invalidation, JSON export and viewer permissions; no vendor calls.');
}finally{await browser.close();}
